// Helper function to get day by number
export function getDayContent(dayNumber: number): DayContent | undefined {
  for (const week of curriculumData) {
    const day = week.days.find((d) => d.day === dayNumber);
    if (day) return day;
  }
  return undefined;
}

// Helper function to get week by number
export function getWeekContent(weekNumber: number): WeekContent | undefined {
  return curriculumData.find((w) => w.week === weekNumber);
}

// Get all days as flat array
export function getAllDays(): DayContent[] {
  return curriculumData.flatMap((week) => week.days);
}

